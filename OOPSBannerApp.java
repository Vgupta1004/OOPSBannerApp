class OOPSBannerApp3{
	public static void main(String args[]){
		System.out.println();
		System.out.println(String.join(" ","  ***  ","  ***  ","****  ","  ***** "));
		System.out.println(String.join(" "," ** ** "," ** ** ","**  **"," **   **"));
		System.out.println(String.join(" ","**   **","**   **","**  **","**      "));
		System.out.println(String.join(" ","**   **","**   **","****  ","  ***** "));
		System.out.println(String.join(" ","**   **","**   **","**    ","      **"));
		System.out.println(String.join(" "," ** ** "," ** ** ","**    ","**   ** "));
		System.out.println(String.join(" ","  ***  ","  ***  ","**    "," *****  "));
		System.out.println();
	}
}
